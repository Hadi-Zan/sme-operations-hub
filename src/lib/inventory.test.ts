import { describe, expect, it } from "vitest";
import {
  formatInventoryAttentionDetail,
  formatInventoryQuantity,
} from "./inventory";

describe("inventory quantity formatting", () => {
  it("removes unnecessary decimal zeros from whole quantities", () => {
    expect(formatInventoryQuantity(10)).toBe("10");
    expect(formatInventoryQuantity(-6)).toBe("-6");
    expect(formatInventoryQuantity(10_000)).toBe("10,000");
  });

  it("preserves readable precision for stored decimal quantities", () => {
    expect(formatInventoryQuantity(2.5)).toBe("2.5");
    expect(formatInventoryQuantity(3.125)).toBe("3.125");
    expect(formatInventoryQuantity(0.001)).toBe("0.001");
  });

  it("normalizes the inventory detail generated by the attention view", () => {
    expect(
      formatInventoryAttentionDetail(
        "10.000 units remaining; reorder at 10.000 units",
      ),
    ).toBe("10 units remaining; reorder at 10 units");

    expect(
      formatInventoryAttentionDetail(
        "2.500 litres remaining; reorder at 3.125 litres",
      ),
    ).toBe("2.5 litres remaining; reorder at 3.125 litres");
  });

  it("leaves unrelated attention detail unchanged", () => {
    const detail = "Task was due 27 Aug 2026";
    expect(formatInventoryAttentionDetail(detail)).toBe(detail);
  });
});
